function safetyChecklist(trend) {
  const checklist = [
    "公式発表、一次情報、日付を確認する",
    "断定を避け、推測は推測として分ける",
    "過度な煽り、晒し、相互フォロー誘導を入れない"
  ];
  if (trend.risk?.riskHits?.length) {
    checklist.unshift(`要注意語: ${trend.risk.riskHits.join(", ")}`);
  }
  return checklist;
}

