function buildVariationFromBank(bank, trend, context, type) {
  return bank.map((angle) => {
    if (type === "x") {
      const hook = substitute(pickRandom(angle.hooks), trend, context);
      const body = substitute(pickRandom(angle.bodies), trend, context);
      const closing = substitute(pickRandom(angle.closings), trend, context);
      return {
        angle: angle.angle,
        hook: hook.split(/[。！？\n]/)[0],
        draft: [hook, body, closing].join("\n\n"),
        hashtags: hashtags(trend.title, context).slice(0, 3)
      };
    }
    if (type === "instagram") {
      const hook = substitute(pickRandom(angle.hooks), trend, context);
      const beats = pickRandom(angle.beatsTemplates).map((b) => substitute(b, trend, context));
      const caption = substitute(pickRandom(angle.captions), trend, context);
      return {
        angle: angle.angle,
        hook,
        beats,
        caption,
        hashtags: hashtags(trend.title, context)
      };
    }
    // note
    const title = substitute(pickRandom(angle.titles), trend, context);
    const outline = pickRandom(angle.outlines).map((o) => substitute(o, trend, context));
    const lead = substitute(pickRandom(angle.leads), trend, context);
    return {
      angle: angle.angle,
      title,
      outline,
      lead
    };
  });
}

function makeXVariations(trend, context) {
  return buildVariationFromBank(X_BANK, trend, context, "x");
}

