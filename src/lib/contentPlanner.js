const pickRandom = (arr) => arr[Math.floor(Math.random() * arr.length)];

// 語彙シノニム（ランダム置換）。「する」が後に続くテンプレで使うため、すべて名詞形またはサ変名詞で統一。
const VOCAB = {
  本質: ["本質", "コア", "急所", "核心", "肝"],
  影響: ["影響", "波及", "効果", "実害", "メリット"],
  重要: ["大事", "クリティカル", "見逃せない", "外せない", "鍵"],
  確認: ["確認", "裏取り", "ファクトチェック", "検証", "精査"],
  整理: ["整理", "棚卸し", "見える化", "切り分け", "腑分け"],
  落とし穴: ["落とし穴", "罠", "つまずきポイント", "盲点", "ハマりやすい点"],
  盛り上がり: ["盛り上がり", "話題化", "ざわつき", "ブーム", "騒動"],
  ポイント: ["ポイント", "観点", "切り口", "視点", "論点"],
  検証: ["検証", "実験", "テスト", "試行", "実証"],
  考える: ["考えます", "捉えます", "読み解きます", "解釈します", "判断します"]
};

function substitute(text, trend, context) {
  if (!text) return "";
  const topic = trend.title;
  const a = audience(context);
  const n = niche(context);
  const s = stance(context);
  let out = String(text)
    .replace(/\$\{topic\}/g, topic)
    .replace(/\$\{audience\}/g, a)
    .replace(/\$\{niche\}/g, n)
    .replace(/\$\{stance\}/g, s);
  // シノニム置換: ${本質} 等
  out = out.replace(/\$\{([^}]+)\}/g, (_, key) => {
    if (VOCAB[key]) return pickRandom(VOCAB[key]);
    return `\${${key}}`;
  });
  return out;
}

